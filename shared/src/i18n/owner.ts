const WORDS: Partial<Record<Locale, Record<OwnerKey, string>>> = { en: OWNER_EN, tr: OWNER_TR };

/** One word of the owner console in Turkish or English; any other language reads English. */
export function ownerWord(locale: Locale, key: OwnerKey, vars?: Record<string, string | number>): string {
  const s = (WORDS[locale] ?? OWNER_EN)[key] ?? OWNER_EN[key] ?? key;
  return vars ? s.replace(/\{(\w+)\}/g, (m, k: string) => (k in vars ? String(vars[k]) : m)) : s;
}

/** The two languages the owner console offers. */
export const OWNER_LOCALES: Locale[] = ['tr', 'en'];
