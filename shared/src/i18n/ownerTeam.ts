export function teamWord(locale: Locale, key: TeamKey, vars?: Record<string, string | number>): string {
  const s = (locale === 'tr' ? TEAM_TR : TEAM_EN)[key] ?? TEAM_EN[key] ?? key;
  return vars ? s.replace(/\{(\w+)\}/g, (m, k) => (k in vars ? String(vars[k]) : m)) : s;
}

