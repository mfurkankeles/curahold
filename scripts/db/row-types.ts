// Writes api/src/db/rows.gen.ts: one TypeScript interface per database table, read from the schema the
// migrations build (an in-memory PGlite, nothing outside this machine). Routes pass these to q.query<…>()
// so a misspelt column or a wrong type is a type error instead of `undefined` at run time.
//
//   npx tsx scripts/db/row-types.ts           write the file
//   npx tsx scripts/db/row-types.ts --check   exit 1 when the file is out of date (after a new migration)
//
// Run it after adding a migration (docs/DEVELOPER.md, "Database"). Types only: nothing here runs in the app.
import { readFileSync, writeFileSync } from 'node:fs';
import { join } from 'node:path';
import { createMemoryPg, pgliteDb } from '../../api/src/db/pglite';
import { migrate } from '../../api/src/db/migrate';
import { loadMigrations } from '../../api/src/db/migrations-fs';

const OUT = join(import.meta.dirname, '..', '..', 'api', 'src', 'db', 'rows.gen.ts');

// How each Postgres type arrives in JavaScript through both drivers (PGlite in tests, postgres.js in production).
// 64-bit integers and numerics can come back as text from postgres.js, so they are typed as either; timestamps
// arrive as Date from both. JSON columns hold shapes defined in shared/src, so they stay open (`Json`) and are
// narrowed where they are read.
const TS: Record<string, string> = {
  text: 'string',
  'character varying': 'string',
  character: 'string',
  citext: 'string',
  uuid: 'string',
  inet: 'string',
  bytea: 'Uint8Array',
  boolean: 'boolean',
  smallint: 'number',
  integer: 'number',
  real: 'number',
  'double precision': 'number',
  bigint: 'number | string',
  numeric: 'number | string',
  date: 'Date | string',
  'timestamp with time zone': 'Date',
  'timestamp without time zone': 'Date',
  interval: 'string',
  json: 'Json',
  jsonb: 'Json',
  tsvector: 'string',
};
const ARRAY: Record<string, string> = { _text: 'string[]', _uuid: 'string[]', _int4: 'number[]', _int8: '(number | string)[]', _varchar: 'string[]', _date: '(Date | string)[]', _jsonb: 'Json[]' };

/** The interface name for a table: `audit_log` → `AuditLogRow`. */
const nameOf = (table: string) => table.replace(/(^|_)([a-z0-9])/g, (_, __, ch: string) => ch.toUpperCase()) + 'Row';

/** The generated file's text, from a freshly migrated in-memory database. */
async function generate(): Promise<string> {
  const pg = await createMemoryPg();
  const db = pgliteDb(pg);
  await migrate(db, loadMigrations());
  const cols = await db.system((q) =>
    q.query<{ table_name: string; column_name: string; data_type: string; udt_name: string; is_nullable: string }>(
      `select c.table_name, c.column_name, c.data_type, c.udt_name, c.is_nullable
         from information_schema.columns c
         join information_schema.tables t on t.table_schema = c.table_schema and t.table_name = c.table_name and t.table_type = 'BASE TABLE'
        where c.table_schema = 'public'
        order by c.table_name, c.ordinal_position`,
    ),
  );
  await db.close();
  const tables = new Map<string, string[]>();
  const unknown = new Set<string>();
  for (const c of cols) {
    let ts = c.data_type === 'ARRAY' ? ARRAY[c.udt_name] : (TS[c.data_type] ?? (c.data_type === 'USER-DEFINED' ? 'string' : undefined));
    if (!ts) {
      unknown.add(`${c.data_type}/${c.udt_name}`);
      ts = 'unknown';
    }
    const type = c.is_nullable === 'YES' ? `${ts} | null` : ts;
    const list = tables.get(c.table_name) ?? [];
    list.push(`  ${c.column_name}: ${type};`);
    tables.set(c.table_name, list);
  }
  if (unknown.size) console.warn(`row-types: typed as unknown: ${[...unknown].join(', ')}`);
  const body = [...tables].map(([t, lines]) => `/** Table \`${t}\`. */\nexport interface ${nameOf(t)} {\n${lines.join('\n')}\n}`).join('\n\n');
  return [
    '// GENERATED by scripts/db/row-types.ts from db/migrations — do not edit by hand; run the script after a migration.',
    '// One interface per table, for q.query<…>() (api/src/db/index.ts). Nullable columns are `| null`; a query that',
    '// selects only some columns or joins tables uses Pick<…> of these or its own type.',
    '/* eslint-disable */',
    '',
    '/** A JSON or JSONB column: its shape is defined in shared/src and narrowed where it is read. */',
    '// eslint-disable-next-line @typescript-eslint/no-explicit-any',
    'export type Json = any;',
    '',
    body,
    '',
  ].join('\n');
}

const text = await generate();
if (process.argv.includes('--check')) {
  let current = '';
  try {
    current = readFileSync(OUT, 'utf8');
  } catch {
    /* missing counts as out of date */
  }
  if (current !== text) {
    console.error('api/src/db/rows.gen.ts is out of date: run `npx tsx scripts/db/row-types.ts`.');
    process.exit(1);
  }
  console.log('rows.gen.ts is current.');
} else {
  writeFileSync(OUT, text);
  console.log(`wrote ${OUT} (${(text.match(/^export interface/gm) ?? []).length} tables)`);
}
