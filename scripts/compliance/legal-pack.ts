/** SHA-256 of every legal page in every language that has it. */
export function legalHashes(pages: Map<string, string>): string {
  const docs: Record<string, Record<string, string>> = {};
  const slugs = Object.values(AGREEMENT_PACK).map((d) => d.slug);
  for (const extra of ['legal-privacy', 'legal-kvkk', 'legal-cookies', 'legal-subprocessors']) slugs.push(extra);
  for (const lang of LOCALES)
    for (const slug of slugs) {
      const path = join(DOCS, lang, `${slug}.md`);
      const text = pages.get(path) ?? (existsSync(path) ? readFileSync(path, 'utf8') : null);
      if (text == null) continue;
      (docs[slug] ??= {})[lang] = createHash('sha256').update(text).digest('hex');
    }
  const versions = Object.fromEntries(Object.entries(AGREEMENT_PACK).map(([k, d]) => [k, d.version]));
  return `${JSON.stringify({ versions, sha256: docs }, null, 2)}\n`;
}

export function outputs(): Map<string, string> {
  const out = new Map<string, string>();
  for (const l of LOCALES) out.set(join(DOCS, l, 'legal-subprocessors.md'), subprocessorPage(l));
  for (const lang of ['en', 'tr'] as const) {
    out.set(join(DOCS, lang, 'legal-privacy.md'), withTable(join(DOCS, lang, 'legal-privacy.md'), noticeTable('privacy', lang)));
    out.set(join(DOCS, lang, 'legal-kvkk.md'), withTable(join(DOCS, lang, 'legal-kvkk.md'), noticeTable('kvkk', lang)));
  }
  out.set(join(ROOT, 'docs', 'compliance', 'data-inventory.md'), recordsOfProcessing());
  out.set(join(ROOT, 'docs', 'compliance', 'verbis-hazirlik.md'), verbisSheet());
  out.set(join(ROOT, 'shared', 'src', 'compliance', 'legal-hashes.json'), legalHashes(out));
  return out;
}

const PRINT_CSS =
  'body{font:11pt/1.5 system-ui,"Noto Sans","Noto Sans Arabic","Noto Sans Hebrew","Noto Sans CJK SC",sans-serif;color:#111;margin:0}' +
  'h1{font-size:18pt;margin:0 0 8pt}h2{font-size:13pt;margin:14pt 0 4pt}h3{font-size:11.5pt}' +
  'table{border-collapse:collapse;width:100%;font-size:9pt;margin:6pt 0}th,td{border:1px solid #999;padding:3pt 5pt;vertical-align:top;text-align:start}' +
  'h1 a[href^="#"],h2 a[href^="#"],h3 a[href^="#"]{display:none}' +
  'blockquote{border-inline-start:3pt solid #999;margin:0;padding:2pt 8pt;background:#f3f3f3}a{color:#111}code{font-size:9pt}';

async function pdfs(built: string, outDir: string) {
  const { default: puppeteer } = await import('puppeteer-core');
  const browser = await puppeteer.launch({ executablePath: '/usr/bin/google-chrome', args: ['--no-sandbox'] });
  try {
    const page = await browser.newPage();
    for (const lang of readdirSync(built).filter((l) => (LOCALES as string[]).includes(l)))
      for (const slug of readdirSync(join(built, lang)).filter((s) => s.startsWith('legal-'))) {
        const html = join(built, lang, slug, 'index.html');
        if (!existsSync(html)) continue;
        // The copy carries the article only, in a plain print layout (no menus, no scripts).
        const src = readFileSync(html, 'utf8');
        const article = /<article class="doc">([\s\S]*?)<\/article>/.exec(src)?.[1] ?? src;
        const dir = /<html[^>]*\bdir="(rtl|ltr)"/.exec(src)?.[1] ?? 'ltr';
        await page.setContent(
          `<!doctype html><html lang="${lang}" dir="${dir}"><meta charset="utf-8"><style>${PRINT_CSS}</style><body>${article.replace(/<nav class="pager"[\s\S]*?<\/nav>/, '')}</body></html>`,
          { waitUntil: 'load' },
        );
        mkdirSync(join(outDir, lang), { recursive: true });
        await page.pdf({ path: join(outDir, lang, `${slug}.pdf`), format: 'A4', printBackground: false, margin: { top: '18mm', bottom: '18mm', left: '16mm', right: '16mm' } });
        console.log(`pdf ${lang}/${slug}.pdf`);
      }
  } finally {
    await browser.close();
  }
}

if (process.argv[1] && fileURLToPath(import.meta.url) === process.argv[1]) {
  const args = process.argv.slice(2);
  if (args[0] === '--pdf') {
    await pdfs(args[1] ?? join(ROOT, 'dist', 'web', 'docs'), args[2] ?? join(ROOT, 'dist', 'web', 'docs', 'pdf'));
  } else {
    let bad = 0;
    for (const [path, content] of outputs()) {
      const now = existsSync(path) ? readFileSync(path, 'utf8') : null;
      if (now === content) continue;
      if (args.includes('--check')) {
        console.log(`out of date: ${relative(ROOT, path)}`);
        bad++;
      } else {
        mkdirSync(dirname(path), { recursive: true });
        writeFileSync(path, content);
        console.log(`wrote ${relative(ROOT, path)}`);
      }
    }
    if (bad) process.exit(1);
  }
}
