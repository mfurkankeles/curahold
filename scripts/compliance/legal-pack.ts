// The legal pack, generated from the data inventory (shared/src/compliance/dataInventory.ts).
//
//   npx tsx scripts/compliance/legal-pack.ts           write everything below
//   npx tsx scripts/compliance/legal-pack.ts --check   exit 1 when something is out of date
//   npx tsx scripts/compliance/legal-pack.ts --pdf <built docs dir> <out dir>
//        print a PDF copy of every legal page (headless Chrome, at release time)
//
// Writes: docs/site/<lang>/legal-subprocessors.md (eleven languages); the tables
// between <!-- inventory --> and <!-- /inventory --> in the privacy notice and the
// KVKK notice (every language that has them: English and Turkish from the inventory's
// own words, the others from shared/src/compliance/noticeRows/<lang>.ts); docs/compliance/data-inventory.md (records of
// processing); docs/compliance/verbis-hazirlik.md (VERBİS preparation sheet); and
// shared/src/compliance/legal-hashes.json — the SHA-256 of every legal page per
// language, stored with each click-accept (api/src/lib/agreementEvidence.ts).
import { createHash } from 'node:crypto';
import { existsSync, mkdirSync, readFileSync, readdirSync, writeFileSync } from 'node:fs';
import { dirname, join, relative } from 'node:path';
import { fileURLToPath } from 'node:url';
import { LOCALES, type Locale } from '../../shared/src/i18n/core';
import { ACTIVITIES, COMPANY, SUBPROCESSORS, type Activity, type ProcessorId } from '../../shared/src/compliance/dataInventory';
import { SUB_PAGE } from '../../shared/src/compliance/subprocessorText';
import { AGREEMENT_PACK } from '../../shared/src/compliance/agreements';
import { NOTICE_ROWS, type NoticeLocale } from '../../shared/src/compliance/noticeRows';

const ROOT = join(dirname(fileURLToPath(import.meta.url)), '..', '..');
const DOCS = join(ROOT, 'docs', 'site');
const cell = (s: string) => s.replace(/\|/g, '\\|').replace(/\n/g, ' ');
const row = (cells: string[]) => `| ${cells.map(cell).join(' | ')} |`;
const table = (head: string[], rows: string[][]) => [row(head), `| ${head.map(() => '---').join(' | ')} |`, ...rows.map(row)].join('\n');
const company = (id: ProcessorId) => SUBPROCESSORS.find((s) => s.id === id)!.company;

function where(codes: string[], locale: Locale): string {
  const names = new Intl.DisplayNames([locale], { type: 'region' });
  return new Intl.ListFormat([locale], { type: 'conjunction' }).format(codes.map((c) => (c.startsWith('[') ? c : (names.of(c) ?? c))));
}

/** The sub-processor list page in one language, from the processing registry. */
export function subprocessorPage(locale: Locale): string {
  const t = SUB_PAGE[locale];
  const rows = SUBPROCESSORS.map((s) => [s.company, s.purpose[locale], where(s.countries, locale), t.when[s.when]]);
  return [
    '---',
    `title: ${t.title}`,
    'section: legal',
    'order: 5',
    `summary: ${t.summary}`,
    '---',
    '<!-- Generated by scripts/compliance/legal-pack.ts from shared/src/compliance/dataInventory.ts. Do not edit by hand. -->',
    `# ${t.title}`,
    '',
    `> **${t.draft}**`,
    '',
    t.intro,
    '',
    table([t.head.company, t.head.purpose, t.head.where, t.head.when], rows),
    '',
    t.notOurs,
    '',
    t.ai,
    '',
    t.recording,
    '',
  ].join('\n');
}

/** The languages the data inventory writes itself (its Two fields); every other one takes its words from noticeRows. */
const inventorySpeaks = (lang: Locale): lang is keyof Activity['purpose'] => !(lang in NOTICE_ROWS);

/**
 * The table inside the privacy notice / KVKK notice, in one language. Which rows appear, in which order and with
 * which recipients always comes from the inventory; past English and Turkish only the words come from noticeRows,
 * so a translation can never list a provider or a purpose the inventory does not have.
 */
export function noticeTable(kind: 'privacy' | 'kvkk', lang: Locale): string {
  const controller = ACTIVITIES.filter((a) => a.role === 'controller' || kind === 'privacy');
  const mark = '<!-- inventory: generated by scripts/compliance/legal-pack.ts from the data inventory -->';
  if (!inventorySpeaks(lang)) return `${mark}\n${translatedTable(kind, lang as NoticeLocale, controller)}\n<!-- /inventory -->`;
  const recipients = (a: Activity) => [...a.processors.map(company), ...(a.others ? [a.others[lang]] : [])].join('; ');
  const basis = (a: Activity) => {
    if (kind === 'kvkk') return a.basis.tr[lang];
    if (lang !== 'en') return a.basis.tr[lang];
    return `EU/UK: ${a.basis.eu}. Türkiye: ${a.basis.tr.en}. Gulf: ${a.basis.gulf}. Elsewhere: ${a.basis.other}.`;
  };
  const head = {
    tr: ['Amaç', 'Kişisel veriler', 'Kimin verisi', kind === 'kvkk' ? 'Hukuki sebep (KVKK m. 5)' : 'Hukuki dayanak (Türkiye; diğer bölgeler İngilizce sürümde)', 'Saklama süresi', 'Alıcılar'],
    en: ['Purpose', 'Personal data', 'Whose data', kind === 'kvkk' ? 'Legal ground (KVKK art. 5)' : 'Legal basis by region', 'Kept for', 'Recipients'],
  }[lang];
  const rows = controller.map((a) => [
    a.role === 'processor' ? `${a.purpose[lang]} (${{ tr: 'müşteri adına, veri işleyen olarak', en: 'for the customer, as processor' }[lang]})` : a.purpose[lang],
    a.data[lang],
    a.subjects[lang],
    basis(a),
    a.retention[lang],
    recipients(a),
  ]);
  return `${mark}\n${table(head, rows)}\n<!-- /inventory -->`;
}

/** The table in a language past English and Turkish; stops with the file to fix when a row or a cell is missing. */
function translatedTable(kind: 'privacy' | 'kvkk', lang: NoticeLocale, activities: Activity[]): string {
  const t = NOTICE_ROWS[lang];
  const file = `shared/src/compliance/noticeRows/${lang}.ts`;
  const rows = activities.map((a) => {
    const r = t.rows[a.id];
    if (!r) throw new Error(`${file}: no row for activity "${a.id}"`);
    const ground = kind === 'kvkk' ? r.kvkk : r.basis;
    if (!ground) throw new Error(`${file}: activity "${a.id}" has no ${kind === 'kvkk' ? 'kvkk' : 'basis'} cell`);
    if (a.others && !r.others) throw new Error(`${file}: activity "${a.id}" has no "others" (recipients named in words)`);
    return [
      a.role === 'processor' ? `${r.purpose} (${t.processor})` : r.purpose,
      r.data,
      r.subjects,
      ground,
      r.retention,
      [...a.processors.map(company), ...(a.others ? [r.others!] : [])].join('; '),
    ];
  });
  const h = t.head;
  return table([h.purpose, h.data, h.subjects, kind === 'kvkk' ? h.kvkk : h.basis, h.retention, h.recipients], rows);
}

function withTable(path: string, content: string): string {
  const text = readFileSync(path, 'utf8');
  const re = /<!-- inventory[^>]*-->[\s\S]*?<!-- \/inventory -->/;
  if (!re.test(text)) throw new Error(`${relative(ROOT, path)} has no <!-- inventory --> … <!-- /inventory --> block`);
  return text.replace(re, content);
}

/** The records of processing activities (GDPR Art. 30) as Markdown, from the processing registry. */
export function recordsOfProcessing(): string {
  const lines = [
    '# Records of processing (data inventory)',
    '',
    '> Generated by scripts/compliance/legal-pack.ts from shared/src/compliance/dataInventory.ts — edit that file. Draft — lawyer approval required (taslak — avukat onayı gerekli). GDPR art. 30, KVKK (VERBİS), Saudi PDPL (records kept 5 years), Korea PIPA art. 30.',
    '',
    `Controller: ${COMPANY.legalName}, ${COMPANY.address} (${COMPANY.country}). Privacy contact: ${COMPANY.privacyEmail}.`,
    '',
    '## Processing activities',
    '',
  ];
  for (const a of ACTIVITIES) {
    lines.push(
      `### ${a.id} — ${a.purpose.en}`,
      '',
      `- **Role:** ${a.role === 'controller' ? 'Curahold is the controller' : 'Curahold is the processor (the customer is the controller)'}`,
      `- **Data subjects:** ${a.subjects.en}`,
      `- **Personal data:** ${a.data.en}`,
      `- **Legal basis:** Türkiye — ${a.basis.tr.en}; EU/UK — ${a.basis.eu}; Gulf — ${a.basis.gulf}; elsewhere — ${a.basis.other}`,
      `- **Retention:** ${a.retention.en}`,
      `- **Stored with / received by:** ${a.processors.map((p) => (a.transfers?.[p] === 'separate controller' ? `${company(p)} (separate controller)` : company(p))).join(', ')}${a.others ? `; ${a.others.en}` : ''}`,
      `- **VERBİS categories:** ${a.verbis.join(', ')}`,
      '',
    );
  }
  lines.push(
    '## Sub-processor register',
    '',
    table(
      ['Company', 'Purpose', 'Countries', 'When', 'Transfer safeguards', 'KVKK standard contract', 'Handles trial leads'],
      SUBPROCESSORS.map((s) => [s.company, s.purpose.en, s.countries.join(', '), s.when, s.safeguards, s.kvkkStandardContract, s.leads ? 'yes' : 'no']),
    ),
    '',
    '## Security measures',
    '',
    'See the Data processing agreement, Annex 2 (technical and organisational measures), whose source is SECURITY.md.',
    '',
  );
  return lines.join('\n');
}

const KVKK_STATUS: Record<string, string> = { to_ask: 'Sorulacak', signed: 'İmzalandı', notified: 'Kurula bildirildi', not_needed: 'Gerekmiyor' };

/** The VERBİS "transfer abroad" cell: which standard contract each foreign recipient needs (processor or separate controller). */
function abroad(ids: string[]): string {
  const foreign = ids.map((p) => SUBPROCESSORS.find((s) => s.id === p)!).filter((s) => s.countries.some((c) => c !== 'TR'));
  if (!foreign.length) return 'Hayır';
  const own = foreign.filter((s) => s.ownController);
  if (!own.length) return 'Evet — KVKK m. 9 standart sözleşme (veri işleyene aktarım)';
  const processors = foreign.length > own.length ? 'veri işleyenlere aktarım; ' : '';
  return `Evet — KVKK m. 9 standart sözleşme (${processors}${own.map((s) => s.company).join(', ')}: ayrı veri sorumlusuna aktarım, veri sorumlusundan veri sorumlusuna sözleşme)`;
}

